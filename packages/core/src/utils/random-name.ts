function pickRandom<T>(items: ReadonlyArray<T>): T {
  const item = items[Math.floor(Math.random() * items.length)]
  if (item === undefined) {
    throw new Error("Unreachable: word list is never empty")
  }

  return item
}

/** Readable placeholder name for a new device/account, e.g. "swift-otter-482". */
export function createRandomDisplayName(): string {
  const adjective = pickRandom(ADJECTIVES)
  const noun = pickRandom(NOUNS)
  const suffix = Math.floor(Math.random() * 900) + 100

  return `${adjective}-${noun}-${suffix}`
}
